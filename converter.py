# Ask user for distance in miles and convert to kilometers

miles = float(input("Enter distance in miles: "))
kilometers = miles * 1.60934
print(f"{miles} miles is equal to {kilometers:.2f} kilometers")

# Ask user for weight in pounds and convert to kilograms (1 lb = 0.453592 kg)

pounds = float(input("Enter weight in pounds: "))
kilograms = pounds * 0.453592
print(f"{pounds} pounds is equal to {kilograms:.2f} kilograms")